// Public 2D/3D planner sandbox (/try): the real builder in guest mode, browser-only.
// try.html is generated from builder.html (scripts/gen-try.mjs); these checks run on a
// FRESH build of builder.html so they never depend on someone re-running the generator.
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { buildTry } from '../scripts/gen-try.mjs';

const root = new URL('..', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const require = createRequire(import.meta.url);
let n = 0; const t = (name, fn) => { fn(); n++; console.log('ok -', name); };

const html = buildTry(read('public/builder.html'));
const noComments = html.replace(/<!--[\s\S]*?-->/g, '');

t('try.html is public: no auth gate, no Supabase hints, no config/telemetry/photo render', () => {
  assert.ok(!/auth-pending/.test(html));
  assert.ok(!/supabase\.co/.test(noComments));
  assert.ok(!/config\.js|telemetry\.js|photo-render/.test(noComments));
  assert.ok(!/<script>(?!<\/script>)/.test(html), 'no inline scripts (CSP)');
  assert.ok(!/\sstyle="/.test(html), 'no style attributes');
});
t('try.js loads before store-api.js; banner + trial CTA present', () => {
  assert.ok(html.indexOf('/try.js?v=') > 0 && html.indexOf('/try.js?v=') < html.indexOf('store-api.js'));
  assert.match(html, /Sandbox — nothing is saved/);
  assert.match(html, /data-m="2d"[\s\S]*data-m="3d"[\s\S]*data-m="measure"/);
  assert.match(html, /href="\/login\?trial=1#signup"><span class="try-cta-l">Start your 8-day free trial/);
  assert.match(html, /<link rel="canonical" href="https:\/\/www\.helm\.events\/try">/);
});
t('committed public/try.html carries the sandbox shell (regenerate with node scripts/gen-try.mjs)', () => {
  const cur = read('public/try.html');
  assert.match(cur, /GENERATED by scripts\/gen-try\.mjs/);
  assert.ok(!/auth-pending|config\.js|telemetry\.js|photo-render/.test(cur.replace(/<!--[\s\S]*?-->/g, '')));
});

// try.js in a sandbox: Supabase config blanked + network guard
function runTry() {
  const calls = [];
  const store = new Map();
  const win = {
    location: { href: 'https://www.helm.events/try', origin: 'https://www.helm.events', pathname: '/try', search: '' },
    fetch: (...a) => { calls.push(a); return Promise.resolve({ ok: true }); },
    XMLHttpRequest: function () {}, WebSocket: function () {},
    history: { replaceState() {} },
    localStorage: { getItem: (k) => (store.has(k) ? store.get(k) : null), setItem: (k, v) => store.set(k, String(v)) },
  };
  win.XMLHttpRequest.prototype.open = function () {};
  Object.assign(win, { window: win, URL, URLSearchParams, Promise, Object, JSON, String, TypeError,
    navigator: {}, document: { documentElement: { setAttribute() {} }, addEventListener() {}, getElementById: () => null } });
  vm.createContext(win);
  vm.runInContext(read('public/try.js'), win);
  return { win, calls };
}
t('try.js blanks the Supabase config (store-api falls back to localStorage) and flags the sandbox', () => {
  const { win } = runTry();
  assert.equal(win.SUPABASE_CONFIG.url, ''); assert.equal(win.SUPABASE_CONFIG.anonKey, '');
  assert.equal(win.HELM_SANDBOX, true);
  try { win.SUPABASE_CONFIG = { url: 'https://x.supabase.co', anonKey: 'k' }; } catch (e) { /* read-only */ }
  assert.equal(win.SUPABASE_CONFIG.url, '', 'config cannot be replaced later');
});
t('network guard: only same-origin static GETs and the three.js CDN', () => {
  const { win } = runTry();
  const ok = win.__trySandboxOk;
  assert.equal(ok('/builder.js?v=1', 'GET'), true);
  assert.equal(ok('https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js', 'GET'), true);
  for (const [u, m] of [['/api/health', 'GET'], ['/api/layouts', 'POST'], ['/builder.js', 'POST'],
    ['https://nqltzgiwznphugcfhmbm.supabase.co/rest/v1/quotes', 'GET'], ['https://evil.test/x', 'GET'], ['/functions/v1/render-photo', 'GET']])
    assert.equal(ok(u, m), false, m + ' ' + u);
  let blocked = false; win.fetch('/api/health').catch(() => { blocked = true; }).then(() => assert.ok(blocked, 'fetch /api/health must reject'));
});
t('/try is a public marketing page: indexable, builder CSP (3D libs), robots + sitemap', () => {
  const server = require('../server.js');
  assert.ok(server.INDEXABLE_PAGES.has('try'));
  const h = server.securityHeadersFor({ headers: { host: 'www.helm.events' } }, 'try.html');
  assert.match(h['Content-Security-Policy'], /cdnjs\.cloudflare\.com\/ajax\/libs\/three\.js/);
  assert.ok(!h['X-Robots-Tag']);
  assert.match(read('public/robots.txt'), /^Allow: \/try\$$/m);
  assert.match(read('public/sitemap.xml'), /<loc>https:\/\/www\.helm\.events\/try<\/loc>/);
});
console.log(`\ntry-sandbox: ${n} passed`);
