// gen-apply-release-1021.mjs - builds supabase/APPLY-RELEASE-1021.sql: ONE paste for the Supabase SQL editor with
// every database change of release/r20-pr4 (round 20, part 4: the migrations written after release 1020 = 0238,
// APPLY-RELEASE-1020.sql), in MANIFEST (= numeric) order:
//   APPLY-0239 (Business page admin only by default: new 'business' access area)
//   - each paste file verbatim, each in its own begin / commit - then ONE combined VERIFY grid (the last result the
//   editor shows; every row must say ok = true).
// No temp tables, no session settings, no psql meta-commands; safe to paste twice (every section is idempotent).
//   node scripts/gen-apply-release-1021.mjs           rewrite supabase/APPLY-RELEASE-1021.sql
//   node scripts/gen-apply-release-1021.mjs --check   exit 1 if it is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const ROOT = new URL('..', import.meta.url).pathname;
const r = (p) => readFileSync(ROOT + p, 'utf8');
const OUT = 'supabase/APPLY-RELEASE-1021.sql';

// plain-words header for each section (what it does for the owner, in one or two lines)
const WHAT = {
  '0239': 'Business page = admin only by default: a new access switch "Business overview (studio money)" (area business) - one row per role per studio, admin on, every other role off (insert only, no existing access row changed); new studios get the same; vendor_payables_summary() + business_pnl() (Business page only) also need it. Planners keep Budget & finance for payments / settlement / closure.',
};
// the release = these migrations, in MANIFEST order. FROZEN once shipped: later work gets its own paste file.
export const RELEASE_1021 = ['0239'];

const man = r('supabase/migrations/MANIFEST');
const nums = [...man.matchAll(/^forward  supabase\/migrations\/(\d{4})_/gm)].map((m) => m[1]).filter((n) => RELEASE_1021.includes(n));
if (nums.join() !== RELEASE_1021.join()) throw new Error('MANIFEST does not list the 1021 migrations once each, in order: ' + nums.join());
export const SECTIONS = nums;
const sections = nums.map((n) => {
  const p = `supabase/APPLY-${n}.sql`;
  if (!existsSync(ROOT + p)) throw new Error(p + ': paste file missing for migration ' + n);
  if (!WHAT[n]) throw new Error(p + ': no plain-words header in WHAT');
  return { n, p };
});

const VSTART = 'select item, ok from (values\n';
const VEND_AT = '\n) v(item, ok) order by item;';
const verify = [];
let body = '';
sections.forEach((s, i) => {
  const src = r(s.p).replace(/\s*$/, '\n');
  if (/[^\x09\x0a\x0d\x20-\x7e]/.test(src)) throw new Error(s.p + ': not ASCII');
  if (/^\s*\\/m.test(src)) throw new Error(s.p + ': psql meta-command (not pasteable)');
  if (/\bcreate\s+(temp|temporary)\s+table\b/i.test(src)) throw new Error(s.p + ': temp table (not pasteable)');
  if (/^\s*(set\s+(session\s+)?(role|search_path|statement_timeout|lock_timeout|session_replication_role|"?[a-z_]+\.[a-z_]+"?)\s*(=|to)\s|reset\s+\w)/im.test(src)) throw new Error(s.p + ': session setting (not pasteable)');
  if (!/^begin;$/m.test(src) || !/^commit;$/m.test(src)) throw new Error(s.p + ': no begin; / commit;');
  body += `\n-- ##########################################################################################\n`
        + `-- RELEASE SECTION ${String(i + 1).padStart(2, '0')}/${sections.length}: ${s.p.replace('supabase/', '')}\n`
        + `-- In plain words: ${WHAT[s.n]}\n`
        + `-- ##########################################################################################\n` + src;
  const at = src.lastIndexOf(VSTART), end = at < 0 ? -1 : src.indexOf(VEND_AT, at);
  if (at < 0 || end < 0) throw new Error(s.p + ': VERIFY block missing or not in the expected shape');
  verify.push(`select '${s.n} ' || item as item, ok from (values\n${src.slice(at + VSTART.length, end)}\n) v(item, ok)`);
});

const list = sections.map((s, i) => `--   ${String(i + 1).padStart(2, '0')}  ${s.p.replace('supabase/', '').padEnd(16)} ${WHAT[s.n]}`).join('\n');
const out = `-- APPLY-RELEASE-1021.sql - ONE paste for the Supabase SQL editor: every database change of release/r20-pr4
-- (round 20, part 4: the Business page becomes admin only by default; the rest of part 4 is website-only).
-- GENERATED by scripts/gen-apply-release-1021.mjs from the paste files below - edit those, not this.
-- Run on STAGING first, check the last result grid, then on PRODUCTION only when the owner says go.
-- Works on a database at release 1020 (APPLY-RELEASE-1020.sql = 0238; 0239 does not depend on 0238, so the order
-- of the two pastes does not matter). Needs phase29 / phase57 + 0049 + 0072 + 0124 + 0142 (all on production).
--
-- What it runs, in this order (each section is that file unchanged; each migration in its own transaction):
${list}
-- Rows are only ADDED (role_access: one 'business' row per role per studio, on conflict do nothing); no existing row
-- is changed or deleted. Two functions are renamed once to *__pre0239 (kept, not callable by the app) behind new
-- wrappers with the same names and inputs; _a49_default_matrix() is re-issued (its other 297 rows checked equal
-- first). No table / column / policy changed. Nothing is dropped, deleted or overwritten.
-- Safe to paste twice: every section is idempotent (the second paste changes nothing).
-- If a section stops with an error, fix the cause and paste the whole file again.
-- After it: deploy the site right away (docs/release/RELEASE-1021-OWNER-STEPS.md) - until then a non-admin who still
-- has the old Business page open sees its money cards fail to load (the database already refuses them). No edge function changed in this release.
--
-- The LAST result grid is the combined VERIFY: every row must say ok = true.
${body}
-- ##########################################################################################
-- COMBINED VERIFY (every section's checks; every row must say ok = true)
-- ##########################################################################################
select item, ok from (
${verify.join('\nunion all\n')}
) z order by item;
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(ROOT + OUT) ? r(OUT) : '';
  if (cur !== out) { console.error(`${OUT} is out of date - run: node scripts/gen-apply-release-1021.mjs`); process.exit(1); }
  console.log(`${OUT} is current (${sections.length} sections)`);
} else {
  writeFileSync(ROOT + OUT, out);
  console.log(`wrote ${OUT} (${sections.length} sections, ${verify.length} VERIFY blocks)`);
}
