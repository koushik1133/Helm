// gen-apply-0155-0158.mjs - rebuilds the paste files for the audit run-3 release from the canonical
// migrations: APPLY-0155..0158.sql (one each) and APPLY-0155-0158.sql (all four, in MANIFEST order,
// ONE transaction, every VERIFY row at the very end). `--check` fails if a file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
const ROOT = new URL('..', import.meta.url).pathname;
const r = (p) => readFileSync(ROOT + p, 'utf8');
const LIST = [
  ['0155', 'supabase/migrations/0155_audit_medium_fixes.sql'],
  ['0156', 'supabase/migrations/0156_audit_p2_db_low.sql'],
  ['0157', 'supabase/migrations/0157_privacy_pin.sql'],
  ['0158', 'supabase/migrations/0158_mfa_verify_hook.sql'],
];
// r23-0260 wraps verify_and_consent (and 27 more link entry points) once more: an old copy of 0156 must
// refuse to run on such a database (re-running it would put back a body without the "cancelled" check).
const GUARD = `do $a156guard$ begin
  if to_regprocedure('public.verify_and_consent__pre0260(uuid, text, text, boolean, text, text, text, text)') is not null then
    raise exception 'superseded - do not re-run this legacy bundle on a database that has newer canonical migrations (see supabase/migrations/MANIFEST)';
  end if;
end $a156guard$;
`;
const out = {};
for (const [n, p] of LIST) {
  const cur = r(`supabase/APPLY-${n}.sql`);
  const head = cur.split('\n').slice(0, 2).join('\n');   // keep the two hand-written header lines
  out[`supabase/APPLY-${n}.sql`] = head + '\nbegin;\n' + (n === '0156' ? GUARD : '') + r(p).replace(/\s*$/, '\n') + '\ncommit;\n';
}
const V = '-- VERIFY (read-only): every row must say ok = true\n';
let body = '', verify = [];
for (const [n, p] of LIST) {
  const src = r(p);
  const i = src.lastIndexOf(V);
  if (i < 0) throw new Error(p + ': no VERIFY block');
  const v = src.slice(i + V.length).trim();
  const m = v.match(/^select item, ok from \(values\n([\s\S]*)\n\) v\(item, ok\);$/);
  if (!m) throw new Error(p + ': VERIFY block is not the last statement in the expected shape');
  body += `\n-- ======================== ${p} ========================\n` + src.slice(0, i).replace(/\s*$/, '\n');
  verify.push(`select '${n} ' || item as item, ok from (values\n${m[1]}\n) v(item, ok)`);
}
const combined = `-- APPLY-0155-0158.sql - ONE paste for the Supabase SQL editor (staging first, then prod).
-- Applies 0155, 0156, 0157, 0158 in MANIFEST order inside ONE transaction (all or nothing), then shows
-- every VERIFY row (all must say ok = true). Additive + idempotent, zero data loss: new tables /
-- columns / triggers, functions wrapped with their old bodies kept (*__pre0155 / *__pre0156). No rows
-- deleted. Safe to run twice. Generated by scripts/gen-apply-0155-0158.mjs - edit the migrations, not this.
begin;
${GUARD}${body}
-- ======================== VERIFY: every row must say ok = true ========================
${verify.join('\nunion all\n')}
order by 1;

commit;
`;
out['supabase/APPLY-0155-0158.sql'] = combined;
let bad = 0;
for (const [p, s] of Object.entries(out)) {
  if (/[^\x00-\x7f]/.test(s)) { console.error('non-ASCII in ' + p); bad++; }
  if (process.argv.includes('--check')) { let cur = ''; try { cur = r(p); } catch {} if (cur !== s) { console.error(p + ' is out of date (node scripts/gen-apply-0155-0158.mjs)'); bad++; } }
  else writeFileSync(ROOT + p, s);
}
if (bad) process.exit(1);
console.log(process.argv.includes('--check') ? 'APPLY-0155..0158 up to date' : 'wrote ' + Object.keys(out).join(', '));
