if (!isMain) { /* imported (tests): export only */ }
else if (check) {
  let cur = ''; try { cur = readFileSync(OUT, 'utf8'); } catch (e) {}
  if (cur !== out) { console.error('public/try.html is stale — run: node scripts/gen-try.mjs'); process.exit(1); }
  console.log('try.html up to date');
} else { writeFileSync(OUT, out); console.log('wrote public/try.html'); }
