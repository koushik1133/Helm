// gen-apply-release-1018-c.mjs - builds supabase/APPLY-RELEASE-1018-C.sql: ONE paste for the Supabase SQL editor with
// every database change of release/1018-c (the migrations after 0205, the last one in production with release 1018-b),
// in MANIFEST order:
//   APPLY-0206 (quote in progress), APPLY-0207 (trial terms "I agree"), APPLY-0208 (empty-draft clean-up check),
//   APPLY-0236 (one free-trial definition),
//   APPLY-0237 (trial sample data complete) - each paste file verbatim, each in its own begin / commit -
//   then ONE combined VERIFY grid (the last result the editor shows; every row must say ok = true).
// No temp tables, no session settings, no psql meta-commands; safe to paste twice (every section is idempotent).
//   node scripts/gen-apply-release-1018-c.mjs           rewrite supabase/APPLY-RELEASE-1018-C.sql
//   node scripts/gen-apply-release-1018-c.mjs --check   exit 1 if it is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const ROOT = new URL('..', import.meta.url).pathname;
const r = (p) => readFileSync(ROOT + p, 'utf8');
const OUT = 'supabase/APPLY-RELEASE-1018-C.sql';
export const PROD_LAST = 205;   // production after release 1018-b

// plain-words header for each section (what it does for the owner, in one or two lines)
const WHAT = {
  '0206': '"Continue where you left off" stays until the quote is finished: the step each person last worked on is kept on the server (new table quote_flow_progress + 4 functions).',
  '0207': 'Free-trial terms "I agree": the trial owner\'s agreement (or a teammate\'s notice) is recorded once per terms version (new table trial_terms_acceptances, kept as a consent record).',
  '0208': 'Empty draft quotes are cleaned up again: the quotes check quotes_deleted_reason_chk now also allows the clean-up reason \'auto_empty_draft\' (superset of today\'s values; no row written).',
  '0236': 'One meaning of "in the free trial": checkout-started trials get the trial screens + client Test mode; package / message settings and sample clear / reset / switch refused in the trial; the admin\'s linked staff row is not a staff slot.',
  '0237': 'Trial sample data complete: layout version 1 on every sample event, floor plans seat the guests, event menu plans, layout rules + chair / plate types; existing trials get missing rows (insert only); new sample version.',
};

// the new migrations = every MANIFEST entry numbered after PROD_LAST, in MANIFEST order
const man = r('supabase/migrations/MANIFEST');
const nums = [...man.matchAll(/^forward  supabase\/migrations\/(\d{4})_/gm)].map((m) => m[1]).filter((n) => +n > PROD_LAST);
export const SECTIONS = nums;
const sections = nums.map((n) => {
  const p = `supabase/APPLY-${n}.sql`;
  if (!existsSync(ROOT + p)) throw new Error(p + ': paste file missing for migration ' + n);
  if (!WHAT[n]) throw new Error(p + ': no plain-words header in WHAT');
  return { n, p };
});

const VSTART = 'select item, ok from (values\n';
const VEND_AT = '\n) v(item, ok) order by item;';
const verify = [];
let body = '';
sections.forEach((s, i) => {
  const src = r(s.p).replace(/\s*$/, '\n');
  if (/[^\x09\x0a\x0d\x20-\x7e]/.test(src)) throw new Error(s.p + ': not ASCII');
  if (/^\s*\\/m.test(src)) throw new Error(s.p + ': psql meta-command (not pasteable)');
  if (/\bcreate\s+(temp|temporary)\s+table\b/i.test(src)) throw new Error(s.p + ': temp table (not pasteable)');
  if (/^\s*(set\s+(session\s+)?(role|search_path|statement_timeout|lock_timeout|session_replication_role|"?[a-z_]+\.[a-z_]+"?)\s*(=|to)\s|reset\s+\w)/im.test(src)) throw new Error(s.p + ': session setting (not pasteable)');
  if (!/^begin;$/m.test(src) || !/^commit;$/m.test(src)) throw new Error(s.p + ': no begin; / commit;');
  body += `\n-- ##########################################################################################\n`
        + `-- RELEASE SECTION ${String(i + 1).padStart(2, '0')}/${sections.length}: ${s.p.replace('supabase/', '')}\n`
        + `-- In plain words: ${WHAT[s.n]}\n`
        + `-- ##########################################################################################\n` + src;
  const at = src.lastIndexOf(VSTART), end = at < 0 ? -1 : src.indexOf(VEND_AT, at);
  if (at < 0 || end < 0) throw new Error(s.p + ': VERIFY block missing or not in the expected shape');
  verify.push(`select '${s.n} ' || item as item, ok from (values\n${src.slice(at + VSTART.length, end)}\n) v(item, ok)`);
});

const list = sections.map((s, i) => `--   ${String(i + 1).padStart(2, '0')}  ${s.p.replace('supabase/', '').padEnd(16)} ${WHAT[s.n]}`).join('\n');
const out = `-- APPLY-RELEASE-1018-C.sql - ONE paste for the Supabase SQL editor: every database change of release/1018-c
-- (QA fixes of the 1018 release build, trial terms "I agree", quotes in progress, calendar events view).
-- GENERATED by scripts/gen-apply-release-1018-c.mjs from the paste files below - edit those, not this.
-- Run on STAGING first, check the last result grid, then on PRODUCTION only when the owner says go.
-- Works on a database at the current production state (migrations up to 0${PROD_LAST}, release 1018-b).
--
-- What it runs, in this order (each section is that file unchanged; each migration in its own transaction):
${list}
-- Rows are only written where a section says so: 0237 (the sample master studio: layout version 1 / floor plans /
-- event plans / layout rules / chair + plate types, one new sample version; existing FREE-TRIAL studios: only the
-- missing sample rows, insert only). Paid studios are not changed. Everything else is new tables, functions,
-- wrappers (old bodies kept as *__pre0236), triggers, policies and grants. Nothing is deleted or overwritten.
-- Safe to paste twice: every section is idempotent (the second paste changes nothing).
-- If a section stops with an error, fix the cause and paste the whole file again.
--
-- The LAST result grid is the combined VERIFY: every row must say ok = true.
${body}
-- ##########################################################################################
-- COMBINED VERIFY (every section's checks; every row must say ok = true)
-- ##########################################################################################
select item, ok from (
${verify.join('\nunion all\n')}
) z order by item;
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(ROOT + OUT) ? r(OUT) : '';
  if (cur !== out) { console.error(`${OUT} is out of date - run: node scripts/gen-apply-release-1018-c.mjs`); process.exit(1); }
  console.log(`${OUT} is current (${sections.length} sections)`);
} else {
  writeFileSync(ROOT + OUT, out);
  console.log(`wrote ${OUT} (${sections.length} sections, ${verify.length} VERIFY blocks)`);
}
